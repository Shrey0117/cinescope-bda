OUTPUT_DIR = "output"

@st.cache_data(show_spinner=False)
def load_data():
    """Load pre-computed CSVs generated by recommender.py"""
    out = {}
    files = {
        "metrics":       "model_metrics.csv",
        "genre_stats":   "genre_stats.csv",
        "top_movies":    "top_movies.csv",
        "rating_dist":   "rating_distribution.csv",
        "user_stats":    "user_stats.csv",
        "movies":        "movies.csv",
        "users":         "users.csv",
        "all_recs":      "all_recommendations.csv",
    }
    for key, fname in files.items():
        path = os.path.join(OUTPUT_DIR, fname)
        if os.path.exists(path):
            out[key] = pd.read_csv(path)
    return out

